const TABS = [
  { id: 'basics', icon: '🎲', label: 'شروع', body: Basics },
  { id: 'hits', icon: '💥', label: 'زدن و امتیاز', body: Hits },
  { id: 'squares', icon: '⚡', label: 'خانه‌ها و جعبه', body: Squares },
  { id: 'heroes', icon: '🦸', label: 'هیروها', body: Heroes },
  { id: 'world', icon: '🐉', label: 'اژدها و اتفاق‌ها', body: World },
  { id: 'more', icon: '🏅', label: 'مدال‌ها و بیشتر', body: More },
] as const;
type TabId = (typeof TABS)[number]['id'];

const TAB_KEY = 'howto-tab';

/** The last tab looked at, on this device. */
function savedTab(): TabId {
  try {
    const id = localStorage.getItem(TAB_KEY);
    return TABS.some((t) => t.id === id) ? (id as TabId) : 'basics';
  } catch {
    return 'basics';
  }
}

/** The full rules and scoring, in Persian, in tabs by topic. */
export function HowToPlay({ onClose }: { onClose: () => void }) {
  const [tab, setTab] = useState<TabId>(savedTab);
  const pick = (id: TabId) => {
    setTab(id);
    try {
      localStorage.setItem(TAB_KEY, id);
    } catch {
      // Private windows may refuse; the tab just isn't remembered.
    }
    document.querySelector('.modal.wide')?.scrollTo({ top: 0 });
  };
  const Body = TABS.find((t) => t.id === tab)!.body;
  return (
    <Modal title="آموزش بازی" onClose={onClose} wide>
      <div className="howto fa" dir="rtl" lang="fa">
        <div className="howto-tabs" role="tablist" aria-label="Topics">
          {TABS.map((t) => (
            <button
              key={t.id}
              role="tab"
              aria-selected={tab === t.id}
              className={`howto-tab${tab === t.id ? ' on' : ''}`}
              onClick={() => pick(t.id)}
            >
              <span aria-hidden>{t.icon}</span>
              {t.label}
            </button>
          ))}
        </div>
        <div className="howto-body" role="tabpanel">
          <Body />
        </div>
      </div>
    </Modal>
  );
}
